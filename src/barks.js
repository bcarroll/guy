const last = {};
// the activities that had no remark before (the Studio, the Bowling Alley): picking theirs draws nothing from Math.random (lines.js)
const NEW_BARKS = ['bowl', 'bowlwatch', 'studiodj', 'studioshow', 'studioparty', 'studiowatch', 'playbass', 'playkeys', 'playxylo', 'playbongos'];
export function barkFor(name) { const l = BARKS[name]; return l ? fresh('bark:' + name, l, !NEW_BARKS.includes(name)) : null; }      // (never the same line twice running: lines.js)
// gate: a robot says at most one remark every `gap` ms
export function barkReady(who, now, gap = 25000) { return !(last[who] && now - last[who] < gap); }
export const barkSpoke = (who, now) => { last[who] = now; };          // (only a remark that was really said starts the wait)
export const resetBarks = () => { for (const k of Object.keys(last)) delete last[k]; resetLines(); };
